// Generate a narrow, independent UI entry from the pinned upstream library.
// The original renderer stays untouched for parity tests and fallback.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { INCOMPLETE_IMAGE_PLACEHOLDER } from "remend";

const [, , target] = process.argv;
// biome-ignore lint/style/useUnicodeRegex: esbuild filters use Go RE2, which rejects the Unicode flag.
const PACKAGE_IMPORT = /^[^./]/;
// biome-ignore lint/style/useUnicodeRegex: esbuild filters use Go RE2, which rejects the Unicode flag.
const SOURCE_CHUNK = /streamdown\/dist\/chunk-7TTQLYRW\.js$/;
if (!target) {
  throw new Error(
    "Pass the isolated pnpm patch directory as the output target"
  );
}
const entry = fileURLToPath(import.meta.resolve("streamdown"));
const source = resolve(dirname(entry), "chunk-7TTQLYRW.js");
const original = await readFile(source, "utf8");
const digest = createHash("sha256").update(original).digest("hex");
if (
  digest !== "fa45911f6e80717d03ed271d647135cd958faec11afc541d9928b5fbbaf2fc6a"
) {
  throw new Error(
    "Streamdown source changed; review the UI extraction before upgrading"
  );
}
const output = resolve(target, "dist/ui");
const result = await build({
  banner: {
    js: '"use client";\n/* Generated from Streamdown 2.7.1, Apache-2.0. See LICENSE and UI-NOTICE.md. */',
  },
  bundle: true,
  entryNames: "index",
  external: [],
  format: "esm",
  legalComments: "inline",
  metafile: true,
  minify: true,
  outdir: output,
  platform: "browser",
  plugins: [
    {
      name: "static-ui-only",
      setup(builder) {
        builder.onResolve({ filter: PACKAGE_IMPORT }, ({ path }) => ({
          external: true,
          path: ["clsx", "tailwind-merge"].includes(path) ? "cn" : path,
          sideEffects: false,
        }));
        builder.onLoad({ filter: SOURCE_CHUNK }, () => ({
          contents: original
            .replace(
              "import zi,{INCOMPLETE_IMAGE_PLACEHOLDER}from'remend';",
              "import zi from'remend';"
            )
            .replaceAll(
              "INCOMPLETE_IMAGE_PLACEHOLDER",
              JSON.stringify(INCOMPLETE_IMAGE_PLACEHOLDER)
            )
            .replaceAll("memo(", "/*#__PURE__*/memo(")
            .replaceAll("createContext(", "/*#__PURE__*/createContext(")
            .replaceAll("Object.values(on)", "/*#__PURE__*/Object.values(on)")
            .replaceAll("Object.values(Xi)", "/*#__PURE__*/Object.values(Xi)")
            .replaceAll("Jo=new Qt", "Jo=/*#__PURE__*/new Qt")
            .replace(
              "Ct={...defaultSchema,",
              "Ct=/*#__PURE__*/(()=>({...defaultSchema,"
            )
            .replace("}},on={raw:Zo", "}}))(),on={raw:Zo")
            // Neither component is exported by this UI-only entry.
            .replace('Lr.displayName="Block";', "")
            .replace('Ui.displayName="Streamdown";', "")
            .concat("\nexport { Nt as IncompleteFenceContext };\n"),
          loader: "js",
        }));
      },
    },
  ],
  splitting: true,
  stdin: {
    contents: `export { x as defaultComponents, B as StreamdownContext, IncompleteFenceContext } from ${JSON.stringify(source)};`,
    resolveDir: dirname(entry),
    sourcefile: "index.js",
  },
  write: false,
});
const allowed = new Set([
  "react",
  "react/jsx-runtime",
  "react-dom",
  "cn",
  "unist-util-visit-parents",
]);
for (const file of Object.values(result.metafile.outputs)) {
  for (const dependency of file.imports) {
    if (dependency.external && !allowed.has(dependency.path)) {
      throw new Error(`Unexpected dependency in static UI: ${dependency.path}`);
    }
  }
}
await mkdir(output, { recursive: true });
await Promise.all(
  result.outputFiles.map((file) => writeFile(file.path, file.contents))
);
await writeFile(
  resolve(output, "index.d.ts"),
  'import type { Context } from "react";\nexport { defaultComponents, StreamdownContext } from "../index.js";\nexport declare const IncompleteFenceContext: Context<boolean>;\n'
);
const manifestPath = resolve(target, "package.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
manifest.exports["./ui"] = {
  import: "./dist/ui/index.js",
  types: "./dist/ui/index.d.ts",
};
manifest.dependencies.cn = "0.5.0";
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
  resolve(target, "UI-NOTICE.md"),
  `# Static UI entry\n\nDerived from vercel/streamdown 2.7.1 (Apache-2.0), source SHA256 ${digest}.\n\nGenerated by Busy apps/hub/scripts/generate-markdown-ui.mjs. The new UI entry retains upstream components and contexts but removes unused parser exports using pure-allocation annotations. The original entry is unchanged. Class helpers use cn's compatible exports.\n`
);
console.log(
  `Generated ${result.outputFiles.length} UI files (${result.outputFiles.reduce((total, file) => total + file.contents.length, 0)} bytes)`
);
