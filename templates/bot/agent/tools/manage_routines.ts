import { defineDynamic, defineTool } from "eve/tools";
import { z } from "zod";
import { isConsultation, isRoutineExecution } from "../lib/caller";
import { isCodeTaskCompletion } from "../lib/code-task-guards";
import { lazyResult } from "../lib/lazy-tools";
import {
  ALL_DAYS,
  createRoutine,
  deleteRoutine,
  listRoutines,
  stableRoutineId,
  updateRoutine,
} from "../lib/routines";

const time = z
  .string()
  .regex(/^(?:[01]\d|2[0-3]):[0-5]\d$/u, "Use 24-hour HH:mm time");
const timeZone = z
  .string()
  .trim()
  .min(1)
  .refine((value) => {
    try {
      new Intl.DateTimeFormat("en-US", { timeZone: value }).format();
      return true;
    } catch {
      return false;
    }
  }, "Use a valid IANA time zone");
const daysOfWeek = z
  .array(z.number().int().min(0).max(6))
  .min(1)
  .max(7)
  .refine(
    (days) => new Set(days).size === days.length,
    "daysOfWeek cannot contain duplicates"
  );

const create = z
  .object({
    action: z.literal("create"),
    daysOfWeek: daysOfWeek.default([...ALL_DAYS]),
    name: z.string().trim().min(1).max(100),
    prompt: z.string().trim().min(1).max(20_000),
    time,
    timeZone,
  })
  .strict();

const update = z
  .object({
    action: z.literal("update"),
    daysOfWeek: daysOfWeek.optional(),
    enabled: z.boolean().optional(),
    id: z.uuid(),
    name: z.string().trim().min(1).max(100).optional(),
    prompt: z.string().trim().min(1).max(20_000).optional(),
    time: time.optional(),
    timeZone: timeZone.optional(),
  })
  .strict()
  .refine(
    ({
      name: nameValue,
      prompt: promptValue,
      time: timeValue,
      timeZone: timeZoneValue,
      daysOfWeek: daysValue,
      enabled: enabledValue,
    }) =>
      nameValue !== undefined ||
      promptValue !== undefined ||
      timeValue !== undefined ||
      timeZoneValue !== undefined ||
      daysValue !== undefined ||
      enabledValue !== undefined,
    "Provide at least one field to update"
  );

const list = z.object({ action: z.literal("list") }).strict();
const remove = z.object({ action: z.literal("delete"), id: z.uuid() }).strict();

/**
 * Keep one object at the tool boundary. Some tool-calling providers reject the `anyOf` JSON Schema
 * generated by a discriminated union at the root, so action-specific requirements are enforced by
 * this refinement while the model always receives an ordinary object schema.
 */
const inputSchema = z
  .object({
    action: z.enum(["list", "create", "update", "delete"]),
    daysOfWeek: daysOfWeek.optional(),
    enabled: z.boolean().optional(),
    id: z.uuid().optional(),
    name: z.string().trim().min(1).max(100).optional(),
    prompt: z.string().trim().min(1).max(20_000).optional(),
    time: time.optional(),
    timeZone: timeZone.optional(),
  })
  .strict()
  .superRefine((value, ctx) => {
    let branch: typeof list | typeof create | typeof update | typeof remove =
      list;
    if (value.action === "create") {
      branch = create;
    } else if (value.action === "update") {
      branch = update;
    } else if (value.action === "delete") {
      branch = remove;
    }
    const parsed = branch.safeParse(value);
    if (!parsed.success) {
      for (const issue of parsed.error.issues) {
        ctx.addIssue({
          code: "custom",
          message: issue.message,
          path: issue.path,
        });
      }
    }
  });

export type ManageRoutinesInput = z.infer<typeof inputSchema>;

// Routine changes are user-owned state. Consultations and scheduled runs are read-only and do not even receive this tool.
export default defineDynamic((ctx) =>
  isConsultation(ctx.session.auth) ||
  isRoutineExecution(ctx.session.auth) ||
  isCodeTaskCompletion(ctx.session.auth)
    ? null
    : lazyResult("routines", ctx.view, tool)
);

const tool = defineTool({
  availableInSubagents: false,
  description:
    "Save and manage recurring tasks directly from the conversation. When the user asks for work every day or on selected weekdays at a time, create the routine immediately without asking for a form or another confirmation. Infer its name and saved task from the conversation; resolve the time zone from the user's explicit request or the supplied client-context timeZone. Supply a 24-hour time and IANA zone. List, update, pause, resume or delete routines when asked in chat. The saved task runs through this bot's current tools, MCP connections and installed skills. Never create routines from a scheduled execution.",
  async execute(input, ctx) {
    await Promise.resolve();
    const parsed = inputSchema.parse(input);
    // Guard against a call that was offered before the session changed identity.
    if (isRoutineExecution(ctx.session.auth)) {
      throw new Error("Scheduled routine executions cannot manage routines.");
    }
    if (isConsultation(ctx.session.auth)) {
      throw new Error(
        "Routines cannot be changed during a read-only consultation."
      );
    }
    if (isCodeTaskCompletion(ctx.session.auth)) {
      throw new Error("Code task completions cannot manage routines.");
    }
    const signal = ctx.abortSignal;
    if (parsed.action === "list") {
      return listRoutines(undefined, signal);
    }
    if (parsed.action === "create") {
      const { action: _action, ...details } = create.parse(parsed);
      return createRoutine(
        {
          ...details,
          daysOfWeek: details.daysOfWeek ?? [...ALL_DAYS],
          id: stableRoutineId(ctx.session.id, ctx.callId),
        },
        undefined,
        signal
      );
    }
    if (parsed.action === "update") {
      const { action: _action, id, ...patch } = update.parse(parsed);
      return updateRoutine(id, patch, undefined, signal);
    }
    return deleteRoutine(remove.parse(parsed).id, undefined, signal);
  },
  inputSchema,
  label: {
    start: ({ action }) =>
      `${action.charAt(0).toUpperCase()}${action.slice(1)} routine`,
  },
});
